"""Write configuration.yaml from _config.py.

Section 18's layout names a configuration file at the repository root. This
generates it rather than maintaining it by hand, because two files holding
the same constants is two files that can disagree, and the one the code
actually reads would win silently.

``_config.py`` stays authoritative. configuration.yaml is a readable record
of what it contained when the reported results were produced, useful to
someone auditing the protocol without reading Python, and regenerated by
running this script.

Usage
-----
    python scripts/write_configuration.py
"""

import sys
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT / "src"))

from segmentation_benchmark import _config as C  # noqa: E402

OUTPUT = REPO_ROOT / "configuration.yaml"


def quote(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    return f'"{value}"'


def reported_run() -> dict:
    """What the committed results were actually produced with.

    The defaults in _config.py are the protocol as written; a run can
    override them on the command line, and the reported run did - it used
    256x256, the low-compute resolution Section 13 permits. A configuration
    file that states the default next to results produced at something else
    invites exactly one misreading, so the actual values are read back out
    of the results and recorded alongside.
    """
    import json

    raw = REPO_ROOT / "results" / "raw"
    if not raw.is_dir():
        return {}

    sizes, epochs, batches, models = set(), set(), set(), []
    for path in sorted(raw.glob("*.json")):
        config = json.loads(path.read_text()).get("config", {})
        models.append(path.stem)
        if config.get("input_size"):
            sizes.add(config["input_size"])
        if config.get("epochs"):
            epochs.add(config["epochs"])
        if config.get("batch_size"):
            batches.add(config["batch_size"])

    def one(values):
        if not values:
            return "N/A"
        return values.pop() if len(values) == 1 else sorted(values)

    return {
        "models": models,
        "input_size": one(sizes),
        "epochs": one(epochs),
        "batch_size": one(batches),
    }


def main() -> int:
    classes = "\n".join(
        f"  {index}: {name}" for index, name in enumerate(C.CLASS_NAMES)
    )
    coco_map = "\n".join(
        f"  {coco}: {ours}" for coco, ours in C.COCO_CATEGORY_IDS.items()
    )
    splits = "\n".join(f"  {k}: {v}" for k, v in C.SPLIT_SIZES.items())

    actual = reported_run()
    if actual:
        def field(name, value, explanation):
            """Render a value that may legitimately differ between models.

            A bare YAML list here reads as though the protocol were
            ambiguous. It is not: each model recorded one value, and where
            those differ there is a reason, so the reason is given.
            """
            if not isinstance(value, list):
                return f"  {name}: {value}"
            joined = ", ".join(str(v) for v in value)
            return f"  {name}: \"{joined}\"   # {explanation}"

        epochs_line = field(
            "epochs", actual["epochs"],
            "Mask R-CNN stopped at 14; every other model ran 25",
        )
        batch_line = field(
            "batch_size", actual["batch_size"],
            "K-Means segments one image at a time; the networks use 8",
        )
        run_block = f"""
reported_run:
  # What the committed results in results/ were actually produced with,
  # read back out of them rather than assumed from the defaults above.
  input_size: {actual['input_size']}
{epochs_line}
{batch_line}
  models: {len(actual['models'])}
  note: >-
    Section 13 specifies 512x512 and permits 256x256 where compute is
    limited, applied consistently. The reported run used 256. Mask R-CNN
    completed 14 of 25 epochs; its result file records why under
    config.early_stop_reason.
"""
    else:
        run_block = ""

    document = f"""# Generated by scripts/write_configuration.py on {date.today()}.
#
# src/segmentation_benchmark/_config.py is authoritative: it is what the code
# reads. This file is a readable record of what it held when the reported
# results were produced. Editing this file changes nothing; edit _config.py
# and regenerate.

dataset:
  source: "COCO 2017"
  pool: "train2017 (all three splits drawn from one pool)"
  seed: {C.SEED}
  splits:
{splits}
  classes:
{classes}
  coco_category_id_to_ours:
{coco_map}
  ignore_index: {C.IGNORE_INDEX}
  policies:
    overlap: {quote(C.OVERLAP_POLICY)}
    crowd: {quote(C.CROWD_POLICY)}
    unselected: {quote(C.UNSELECTED_POLICY)}
    minimum_foreground_pixels: {C.MIN_FOREGROUND_PIXELS}

protocol:
  # Section 13. The reported run used 256, the low-compute resolution
  # Section 13 permits, applied consistently to every model; see the README's
  # documented deviations.
  input_size: {C.INPUT_SIZE}
  epochs: {C.EPOCHS}
  batch_size: {C.BATCH_SIZE}
  optimizer: {quote(C.OPTIMIZER)}
  learning_rate: {C.LEARNING_RATE}
  weight_decay: {C.WEIGHT_DECAY}
  mixed_precision: false
  precision: "float32"

loss:
  # Section 16. Semantic models only; instance models keep their own.
  formula: "0.5 * CrossEntropy + 0.5 * Dice"
  cross_entropy_weight: {C.CE_WEIGHT}
  dice_weight: {C.DICE_WEIGHT}
  dice_averaging: "macro over classes present in the batch ground truth"
  class_weighting: "none"

metrics:
  # Section 22 conventions, declared once and applied everywhere.
  background_in_miou: true
  foreground_only_also_reported: true
  absent_classes: "excluded from the mean, not scored zero"
  averaging: "macro over present classes"
  ignored_pixels: "excluded before accumulation"

boundary:
  # Section 24.
  definition: "Csurka et al. 2013 boundary F1"
  tolerance_px: {C.BOUNDARY_TOLERANCE_PX}
  boundary: "inner: region minus its 4-connected erosion"

instance:
  # Section 25.
  evaluator: "pycocotools COCOeval"
  primary_metric: "mask AP over IoU 0.50:0.05:0.95"
  score_threshold: {C.INSTANCE_SCORE_THRESHOLD}
  max_detections: {C.INSTANCE_MAX_DETECTIONS}

measurement:
  # Sections 31 and 33.
  size_convention: "MB = 1024*1024 bytes, weights and buffers, no optimizer state"
  inference_warmup_iterations: {C.INFERENCE_WARMUP_ITERS}
  inference_timed_images: {C.INFERENCE_TIMED_IMAGES}
  inference_batch_sizes: {list(C.INFERENCE_BATCH_SIZES)}
  timed_region: "forward pass only; excludes I/O, preprocessing and transfer"
{run_block}"""
    OUTPUT.write_text(document)
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
